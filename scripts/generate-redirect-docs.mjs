/**
 * Regenerates docs/REDIRECTS.md from vercel.json so the published map can never
 * drift from the actual redirect rules.
 *
 * Run: node scripts/generate-redirect-docs.mjs   (npm run docs:redirects)
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const config = JSON.parse(fs.readFileSync(path.join(root, 'vercel.json'), 'utf8'));

// Collapse the "with trailing slash" duplicate of each path for readability.
const unique = new Map();
for (const rule of config.redirects) {
  const key = rule.source.replace(/\/$/, '');
  if (!unique.has(key)) unique.set(key, rule);
}

const GROUPS = {
  'Pages': [
    /^\/donate-2/, /^\/our-focus/, /^\/independent-prison-oversight/, /^\/prison-oversight/,
    /^\/criminal-legal-system-reform/, /^\/programs\//, /^\/drug-use-risk-mitigation/,
    /^\/returning-citizens/, /^\/arts-in-prison/, /^\/action-center/, /^\/friends/,
    /^\/team-members/, /^\/newsletter/, /^\/contact-us/, /^\/accessibility-statement/,
    /^\/terms-and-conditions/, /^\/privacy-policy/, /^\/digital-literacy/,
  ],
  'Articles': [
    /^\/analysis-of-lewis/, /^\/the-arizona-state-legislature/, /^\/arizona-government/,
    /^\/arizona-department/, /^\/the-legacy-of-mass/, /^\/arizona-prison-independent/,
    /^\/our-fifth-year/, /^\/access-to-courts/,
  ],
  'WordPress artefacts': [/^\/news\/blog/, /^\/blog/, /^\/research/, /^\/feed/, /sitemap/],
};

const lines = [];
lines.push('# Legacy URL Redirects');
lines.push('');
lines.push('All redirects below live in [`vercel.json`](../vercel.json) and are **permanent (308)**, which is');
lines.push('what Google recommends when mapping an old URL to its replacement.');
lines.push('');
lines.push('Both the trailing-slash and non-trailing-slash form of every path is listed in the config, so a');
lines.push('link to either form redirects in a single hop — no redirect chains.');
lines.push('');
lines.push('Source URLs were recovered from the Wayback Machine CDX index for `praxisinitiative.org` and from');
lines.push('the old WordPress `page-sitemap.xml` / `post-sitemap.xml`.');
lines.push('');

const used = new Set();
for (const [name, patterns] of Object.entries(GROUPS)) {
  const rows = [...unique].filter(([key]) => !used.has(key) && patterns.some((p) => p.test(key)));
  if (!rows.length) continue;
  lines.push(`## ${name}`);
  lines.push('');
  lines.push('| Old address | Destination |');
  lines.push('|---|---|');
  for (const [key, rule] of rows) {
    lines.push(`| \`${rule.source}\` | \`${rule.destination}\` |`);
    used.add(key);
  }
  lines.push('');
}

const leftovers = [...unique].filter(([key]) => !used.has(key));
if (leftovers.length) {
  lines.push('## Other');
  lines.push('');
  lines.push('| Old address | Destination |');
  lines.push('|---|---|');
  for (const [, rule] of leftovers) lines.push(`| \`${rule.source}\` | \`${rule.destination}\` |`);
  lines.push('');
}

lines.push('## Adding a redirect');
lines.push('');
lines.push('1. Add **both** forms of the old path (with and without the trailing slash) to the `redirects` array');
lines.push('   in `vercel.json`, and set `"permanent": true`.');
lines.push('2. Point it at a route that actually exists. Every destination can be checked against the build');
lines.push('   output with `npm run check:redirects`.');
lines.push('');
lines.push('## Fragments are not supported in destinations');
lines.push('');
lines.push('Vercel redirect destinations do not reliably carry a `#fragment`. Where an old URL should land on a');
lines.push('specific section, redirect with a query parameter and let the page upgrade it to an anchor. The one');
lines.push('current example: `/digital-literacy-returning-citizens-50-plus/` redirects to');
lines.push('`/training?section=digital-literacy-50-plus`, and `src/pages/TrainingPage.tsx` scrolls to that');
lines.push('element and rewrites the address bar to `/training#digital-literacy-50-plus`.');
lines.push('');
lines.push('## Do not add a catch-all rewrite');
lines.push('');
lines.push('Known routes are real prerendered files (`dist/about.html`, `dist/news/<slug>.html`, …) and unknown');
lines.push('paths must fall through to `dist/404.html` so they return **404** instead of 200. A catch-all');
lines.push('rewrite to `/index.html` would restore the old "everything returns 200" behaviour.');
lines.push('');
lines.push(`_Generated by \`scripts/generate-redirect-docs.mjs\` from ${config.redirects.length} rules — do not edit by hand._`);
lines.push('');

const out = path.join(root, 'docs', 'REDIRECTS.md');
fs.writeFileSync(out, lines.join('\n'));
console.log(`wrote docs/REDIRECTS.md (${unique.size} unique paths, ${config.redirects.length} rules)`);
